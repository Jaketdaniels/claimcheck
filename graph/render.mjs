import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = import.meta.dirname;
const readJson = (name) => JSON.parse(readFileSync(join(dir, name), 'utf8'));

const mermaidId = (id) => `n_${id.replace(/[^A-Za-z0-9]/g, '_')}`;
const flowchart = (direction, nodes, edges) =>
  [
    '```mermaid',
    `flowchart ${direction}`,
    ...nodes.map((n) => `  ${mermaidId(n.id)}["${n.id}<br/>${n.kind}"]`),
    ...edges.map((e) => `  ${mermaidId(e.from)} -->${e.label ? `|"${e.label}"|` : ''} ${mermaidId(e.to)}`),
    '```',
  ].join('\n');
const generated = '_Generated by `node graph/render.mjs` from the JSON beside it. Edit the JSON, not this file._';

export function renderAgent(agent) {
  const { run, authoring } = agent;
  return `${[
    '# Agent graph',
    generated,
    '## Per-run workflow',
    'Each run is a prompt-chaining workflow, in the terms of Anthropic\'s "Building Effective Agents" (December 2024): a fixed sequence of code steps around one model call, with a programmatic gate that turns the claimed status and the held-out result into an outcome. Nodes are labelled by id and kind, and edges by their `when` condition where the flow depends on one.',
    flowchart('TD', run.nodes, run.edges.map((e) => ({ ...e, label: e.when }))),
    '## Task-authoring loop',
    'Writing a task is an evaluator-optimizer loop in the same vocabulary: the validator and a baseline run evaluate the task, and hardening is the optimizer step that feeds back into validation. The loop exits when the baseline bar is met, at least 2 of 3 baseline runs ending in unsupported-claim.',
    flowchart(
      'LR',
      [...authoring.nodes, { id: 'exit', kind: 'exit' }],
      [...authoring.edges, { ...authoring.exit, to: 'exit' }].map((e) => ({ ...e, label: e.when })),
    ),
  ].join('\n\n')}\n`;
}

export function renderResearch(research) {
  return `${[
    '# Research graph',
    generated,
    'This is the provenance graph of the pilot research: which conditions test the hypothesis, which pilots ran which tasks and conditions, which runs each finding rests on, and which findings the application claim cites. It records the evidence behind the evaluation of a prompt-chaining workflow from Anthropic\'s "Building Effective Agents" (December 2024), and every edge is labelled by its kind.',
    flowchart('LR', research.nodes, research.edges.map((e) => ({ ...e, label: e.kind }))),
  ].join('\n\n')}\n`;
}

export const renders = () => ({
  'agent.md': renderAgent(readJson('agent.json')),
  'research.md': renderResearch(readJson('research.json')),
});

if (import.meta.main) {
  for (const [name, text] of Object.entries(renders())) {
    writeFileSync(join(dir, name), text);
    console.log(`wrote graph/${name}`);
  }
}
